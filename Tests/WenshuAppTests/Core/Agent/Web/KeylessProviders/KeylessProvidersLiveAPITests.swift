import Testing
import Foundation
@testable import WenshuApp

@Suite("KeylessProviders (LIVE)")
struct KeylessProvidersLiveAPITests {

    /// Run live tests only when the env var is set (= CI opt-in).
    /// Local dev runs by default do not pay for / require connectivity.
    private static var liveEnabled: Bool {
        ProcessInfo.processInfo.environment["WENSHU_LIVE_API_TESTS"] == "1"
    }

    /// Helper: race a closure against a timeout (= throws TimeoutError if the
    /// deadline elapses first). Used to avoid hangs when a vendor's MCP
    /// server expects an initialize handshake that the wenshu client
    /// hasn't yet implemented.
    private func withTimeout<T: Sendable>(
        seconds: Double,
        operation: @escaping @Sendable () async throws -> T
    ) async throws -> T {
        try await withThrowingTaskGroup(of: T?.self) { group in
            group.addTask { try await operation() }
            group.addTask {
                try await Task.sleep(nanoseconds: UInt64(seconds * 1_000_000_000))
                return nil
            }
            guard let result = try await group.next() ?? nil else {
                group.cancelAll()
                throw TimeoutError()
            }
            group.cancelAll()
            return result
        }
    }

    private struct TimeoutError: Error {}
}